import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { sha256 } from './migration-authority.mjs';
import { CONTENT_CAPABILITIES, STATISTICS_CAPABILITIES } from './schema-completeness.mjs';

// Frozen recovery artefacts are the independent input, never the mutable checkout.
const commit = 'b6d72db5f17ec13b267b25d2f171a42b7f03576a';
const register = JSON.parse(execFileSync('git', ['show', `${commit}:release/central-recovery-migration-register.json`], { encoding: 'utf8' }));
for (const variant of ['checkout-windows', 'git-blob']) {
  const manifests = {};
  for (const [namespace, section, directory] of [['DB', 'content', 'migrations'], ['STATS_DB', 'statistics', 'migrations/statistics']]) {
    const records = register[section].inventory.map(({ name, sha256: hash }) => ({
      name, namespace,
      sha256: variant === 'checkout-windows' ? hash : sha256(execFileSync('git', ['show', `${commit}:${directory}/${name}`])),
    }));
    manifests[namespace] = {
      version: 1, target: { namespace, databaseId: `local-rc-${namespace}`, environment: 'local' },
      approvalRef: 'OWNER_LOCAL_RELEASE_GATE_CLOSURE_2026-10-10',
      provenance: { commit, artifact: variant, productionAuthorized: false },
      baseline: [], authorized: records, order: records.map(r => r.name),
    };
  }
  writeFileSync(`release/local-migration-authority-${variant}.json`, `${JSON.stringify(manifests, null, 2)}\n`);
}
const workstreamNames = Object.fromEntries(Object.entries({ Doctors: /_(doctor|actor)_|_actor_protocol_/, Discovery: /_shared_discovery_|_discovery_signal_/, Protocols: /_protocol_|_actor_protocol_|_claim_|_safety_|_commercial_/, Dossier: /_dossier_/ }).map(([key, pattern]) => [key, register.content.inventory.map(r => r.name).filter(name => pattern.test(name))]));
writeFileSync('apps/worker/src/schema-contract.ts', `// Generated by scripts/generate-local-migration-authority.mjs from frozen recovery authority.\nexport const REQUIRED_CONTENT_MIGRATIONS = ${JSON.stringify(register.content.inventory.map(r => r.name), null, 2)} as const;\nexport const REQUIRED_STATISTICS_MIGRATIONS = ${JSON.stringify(register.statistics.inventory.map(r => r.name), null, 2)} as const;\nexport const WORKSTREAM_MIGRATIONS: Record<string, string[]> = ${JSON.stringify(workstreamNames, null, 2)};\nexport const WORKSTREAM_CAPABILITIES: Record<string, Record<string, string[]>> = ${JSON.stringify(CONTENT_CAPABILITIES, null, 2)};\nexport const STATISTICS_CAPABILITIES: Record<string, string[]> = ${JSON.stringify(STATISTICS_CAPABILITIES, null, 2)};\n`);
console.log('Generated frozen local-only authorities; no production pending set approved.');
