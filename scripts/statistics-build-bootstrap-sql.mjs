// Generates release/statistics-registry-bootstrap.sql: the owner-run production registry bootstrap (item 43). It registers source IDENTITY rows only
// (INSERT OR IGNORE, idempotent), derived from the frozen registry with the SAME mapping the repository bootstrap uses (toSourceInput). It never
// creates a policy row, so every source stays DISABLED (the frozen default), and it contains no ACTIVE or ACTIVATION_GATED value.
//   node scripts/statistics-build-bootstrap-sql.mjs           write the file
//   node scripts/statistics-build-bootstrap-sql.mjs --check   fail when the committed file differs (CI / release gate)
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const OUT = 'release/statistics-registry-bootstrap.sql';
const REGISTRY = 'docs/generated/statistics-source-registry-v1.json';

const bundle = join(mkdtempSync(join(tmpdir(), 'stats-bootstrap-')), 'bootstrap.mjs');
await build({ entryPoints: ['apps/worker/src/statistics/bootstrap.ts'], bundle: true, platform: 'node', format: 'esm', outfile: bundle, logLevel: 'silent' });
const { toSourceInput } = await import(pathToFileURL(bundle).href);

function collect(node, out = []) {
  if (Array.isArray(node)) node.forEach((n) => collect(n, out));
  else if (node && typeof node === 'object') {
    if (typeof node.source_id === 'string' && typeof node.disposition === 'string' && typeof node.area === 'string') out.push(node);
    else Object.values(node).forEach((v) => collect(v, out));
  }
  return out;
}
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`);

export function buildSql() {
  const sources = collect(JSON.parse(readFileSync(REGISTRY, 'utf8'))).sort((a, b) => (a.source_id < b.source_id ? -1 : 1));
  const rows = sources.map((r) => toSourceInput(r));
  const lines = [
    '-- GENERATED by scripts/statistics-build-bootstrap-sql.mjs from docs/generated/statistics-source-registry-v1.json. Do not edit by hand.',
    '-- OWNER-RUN ONLY. Registers source IDENTITY rows in the production STATS_DB (item 43). Idempotent (INSERT OR IGNORE).',
    '-- It creates NO policy row: every source stays DISABLED (the frozen default). It activates nothing.',
    `-- Sources: ${rows.length}`,
    ...rows.map((s) => `INSERT OR IGNORE INTO statistics_sources (source_id, display_name, organization, source_area, disposition, authority_level, upstream_role, official_homepage, architecture_status, registry_version) VALUES (${[s.sourceId, s.displayName, s.organization, s.sourceArea, s.disposition, s.authorityLevel, s.upstreamRole, s.officialHomepage, s.architectureStatus, s.registryVersion].map(q).join(', ')});`),
  ];
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const sql = buildSql();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n'); } catch { /* missing */ }
    if (cur !== sql) { console.error(`${OUT} is stale: run node scripts/statistics-build-bootstrap-sql.mjs`); process.exit(1); }
    console.log(`${OUT} is current (${sql.split('\n').filter((l) => l.startsWith('INSERT')).length} sources)`);
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT}`);
  }
}
