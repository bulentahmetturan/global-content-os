// Derives migrations/statistics/0001_statistics_schema_v1.sql mechanically from the FROZEN reference DDL.
// Usage: node scripts/statistics-build-migration.mjs          (writes the migration)
//        node scripts/statistics-build-migration.mjs --check  (exit 1 if the migration is not exactly header + reference DDL)
// The migration may differ from the reference only by this repository-required header; the body is byte-identical.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

export const REFERENCE = 'docs/generated/statistics-schema-v1.sql';
export const MIGRATION = 'migrations/statistics/0001_statistics_schema_v1.sql';
export const MARKER = '-- ---- BEGIN FROZEN REFERENCE DDL (byte-identical to docs/generated/statistics-schema-v1.sql) ----\n';

export function buildMigration(reference) {
  const sha = createHash('sha256').update(reference).digest('hex');
  const header =
    '-- HEALTH_STATISTICS storage schema V1 — migration 0001 for the dedicated statistics database (future binding STATS_DB).\n' +
    '-- Namespace migrations/statistics/ is private to that database; wrangler\'s default `migrations/*.sql` pattern does not recurse into it,\n' +
    '-- so the content database (binding DB) never sees this file. Not applied to any remote database; no D1 database exists yet.\n' +
    '-- Generated by scripts/statistics-build-migration.mjs — do not edit. apps/worker/src/statistics/migration-drift.test.mjs fails on any drift.\n' +
    `-- reference-ddl-sha256: ${sha}\n`;
  return header + MARKER + reference;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/').replace(/^([A-Za-z]):/, '/$1:')}` || process.argv[1]?.endsWith('statistics-build-migration.mjs')) {
  const lf = (s) => s.split(String.fromCharCode(13, 10)).join(String.fromCharCode(10)); // git autocrlf-neutral
  const reference = lf(readFileSync(REFERENCE, 'utf8'));
  const expected = buildMigration(reference);
  if (process.argv.includes('--check')) {
    let actual = '';
    try {
      actual = lf(readFileSync(MIGRATION, 'utf8'));
    } catch {
      /* missing */
    }
    if (actual !== expected) {
      console.error('DRIFT: migration differs from header + frozen reference DDL');
      process.exit(1);
    }
    console.log('OK: migration == header + frozen reference DDL');
  } else {
    writeFileSync(MIGRATION, expected);
    console.log(`wrote ${MIGRATION} (${expected.length} bytes)`);
  }
}
